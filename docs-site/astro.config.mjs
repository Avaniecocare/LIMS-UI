// The LIMS documentation site. Served at /help/ by the UI's web server, on the same address as the app.
// Branding comes from DOCS_* environment variables at build time, so each lab's copy can carry its own name and colour.
import starlight from '@astrojs/starlight';
import { defineConfig } from 'astro/config';
import { writeFileSync } from 'node:fs';
import { remarkMermaid } from './src/remark-mermaid.mjs';

const env = process.env;
const productName = env.DOCS_PRODUCT_NAME?.trim() || 'LIMS';
const primary = /^#[0-9a-f]{6}$/i.test(env.DOCS_PRIMARY_COLOR ?? '') ? env.DOCS_PRIMARY_COLOR : '#1f4e79';
const site = env.DOCS_SITE_URL?.trim() || 'https://lims.example.com';
// Public docs are indexed by search engines only when the deployment says so.
const indexable = env.DOCS_INDEXABLE === 'true';

// The accent colour, written once per build so Starlight's light and dark themes both use it.
writeFileSync(
  new URL('./src/styles/brand.generated.css', import.meta.url),
  `/* Generated by astro.config.mjs from DOCS_PRIMARY_COLOR. Do not edit. */
:root { --brand: ${primary}; }
:root[data-theme='light'] { --sl-color-accent: ${primary}; --sl-color-accent-high: color-mix(in srgb, ${primary} 70%, black); --sl-color-accent-low: color-mix(in srgb, ${primary} 15%, white); }
:root[data-theme='dark'] { --sl-color-accent: color-mix(in srgb, ${primary} 45%, white); --sl-color-accent-high: color-mix(in srgb, ${primary} 15%, white); --sl-color-accent-low: color-mix(in srgb, ${primary} 35%, black); }
`,
);

const section = (label, directory) => ({ label, items: [{ autogenerate: { directory } }] });

export default defineConfig({
  site,
  base: '/help',
  trailingSlash: 'always',
  markdown: { remarkPlugins: [remarkMermaid] },
  integrations: [
    starlight({
      title: `${productName} help`,
      description: `How to use, run and integrate ${productName}.`,
      logo: env.DOCS_LOGO ? { src: env.DOCS_LOGO, alt: productName } : { src: './src/assets/logo.svg', alt: '' },
      favicon: '/favicon.png',
      // Dates come from git history; container builds have none, so they turn it off.
      lastUpdated: env.DOCS_LAST_UPDATED !== 'false',
      credits: false,
      customCss: ['./src/styles/brand.generated.css', './src/styles/docs.css'],
      head: [
        // Same-origin runtime config from the UI container: tells the Ask AI panel where the API is.
        { tag: 'script', attrs: { src: '/config.js' } },
        ...(indexable ? [] : [{ tag: 'meta', attrs: { name: 'robots', content: 'noindex, nofollow' } }]),
      ],
      components: {
        Footer: './src/components/Footer.astro',
        Head: './src/components/Head.astro',
      },
      sidebar: [
        section('Getting started', 'getting-started'),
        section('Guides by role', 'guides'),
        section('Features', 'features'),
        section('Administration', 'admin'),
        section('Integrations', 'integrations'),
        section('Installation and operations', 'install'),
        section('Developers', 'developers'),
        section('Security and compliance', 'security'),
        section('Troubleshooting', 'troubleshooting'),
        { label: 'Release notes', link: '/changelog/' },
      ],
    }),
  ],
});
